// Default returns the canonical lava mask for idle-king-map (matches TMX Lava layer).
func Default() *LavaMask {
	return &LavaMask{Map: defaultRows}
}

// IsLava reports whether the tile at (row, col) is lava. Out-of-bounds is not lava.
func (m *LavaMask) IsLava(row, col int) bool {
	if m == nil || !world.InBounds(row, col) {
		return false
	}
	return m.Map[row][col] != 0
}

// IsLavaAtWorld returns true if the tile under (px, py) is lava.
func (m *LavaMask) IsLavaAtWorld(px, py float64) bool {
	row, col := world.WorldToTile(px, py)
	return m.IsLava(row, col)
}

// LeftmostLavaCol returns the first column index with lava in row, or world.WidthTiles if none.
func (m *LavaMask) LeftmostLavaCol(row int) int {
	if m == nil || row < 0 || row >= world.HeightTiles {
		return world.WidthTiles
	}
	for c := range world.WidthTiles {
		if m.Map[row][c] != 0 {
			return c
		}
	}
	return world.WidthTiles
}

// RightmostLavaCol returns the last column index with lava in row, or -1 if none.
func (m *LavaMask) RightmostLavaCol(row int) int {
	if m == nil || row < 0 || row >= world.HeightTiles {
		return -1
	}
	last := -1
	for c := range world.WidthTiles {
		if m.Map[row][c] != 0 {
			last = c
		}
	}
	return last
}
